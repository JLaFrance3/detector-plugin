#!/usr/bin/env node
// Generates docs/traceability.md: REQ -> tasks -> tests -> commits.
// Usage: npm run trace   (or: node scripts/trace.mjs [--strict]). No dependencies.
// --strict exits with code 1 when a problem is found (used before finishing a task).
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const rel = (p) => relative(root, p).split(sep).join('/');
const REQ_RE = /REQ-(?:F|UI|NF|SEC|PRV)-\d{3}/g;
const TASK_RE = /TASK-\d{3}/g;

// 1. Requirements: "### REQ-F-001 Title (H)"
const reqText = read(join(root, 'docs/requirements.md'));
const reqs = new Map();
for (const m of reqText.matchAll(/^### (REQ-[A-Z]+-\d{3}) (.+?)(?: \(([HML])\))?$/gm)) {
  reqs.set(m[1], {
    id: m[1],
    title: m[2],
    priority: m[3] ?? '',
    tasks: [],
    tests: new Set(),
    commits: new Set(),
  });
}

// 2. Tasks: frontmatter in tasks/TASK-*.md
const tasks = [];
const taskDir = join(root, 'tasks');
for (const f of readdirSync(taskDir)
  .filter((f) => /^TASK-\d{3}.*\.md$/.test(f))
  .sort()) {
  const text = read(join(taskDir, f));
  const fm = text.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? '';
  const field = (k) => fm.match(new RegExp(`^${k}:\\s*(.*)$`, 'm'))?.[1]?.trim() ?? '';
  const task = {
    id: field('id'),
    title: field('title'),
    status: field('status'),
    file: f,
    requirements: field('requirements').match(REQ_RE) ?? [],
  };
  tasks.push(task);
}

// 3. Tests: any *.spec.ts / *.test.ts / *.test.mjs file mentioning a REQ ID
const testFiles = [];
const walk = (dir) => {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === 'dist' || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(spec|test)\.(ts|js|mjs)$/.test(name)) testFiles.push(p);
    // End-to-end browser checks name the requirement in each check they print.
    else if (dir.endsWith('e2e') && name.endsWith('.mjs') && name !== 'harness.mjs') {
      testFiles.push(p);
    }
  }
};
['extension', 'backend', 'scripts'].forEach((d) => walk(join(root, d)));

// 4. Commits: TASK IDs in git log (optional)
const taskCommits = new Map();
try {
  const log = execSync('git log --pretty=format:%h%x09%s', {
    cwd: root,
    stdio: ['ignore', 'pipe', 'ignore'],
  }).toString();
  for (const line of log.split('\n').filter(Boolean)) {
    const [hash, subject] = line.split('\t');
    for (const t of subject.match(TASK_RE) ?? []) {
      if (!taskCommits.has(t)) taskCommits.set(t, []);
      taskCommits.get(t).push(hash);
    }
  }
} catch {
  /* not a git repo yet */
}

// Link everything
const problems = [];
for (const t of tasks) {
  for (const r of t.requirements) {
    if (reqs.has(r)) reqs.get(r).tasks.push(t);
    else problems.push(`${t.id} references unknown requirement ${r}`);
  }
}
for (const p of testFiles) {
  const text = read(p);
  for (const r of new Set(text.match(REQ_RE) ?? [])) {
    if (reqs.has(r)) reqs.get(r).tests.add(rel(p));
    else problems.push(`${rel(p)} references unknown requirement ${r}`);
  }
}
for (const r of reqs.values()) {
  if (r.tasks.length === 0) problems.push(`${r.id} has no task`);
}

// Write report
const cell = (xs) => (xs.length ? xs.join(', ') : '-');
const out = [
  '# Traceability matrix',
  '',
  `Generated by \`scripts/trace.mjs\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
  '',
  `Requirements: ${reqs.size} · Tasks: ${tasks.length} · Test files: ${testFiles.length} · Tested requirements: ${[...reqs.values()].filter((r) => r.tests.size).length}`,
  '',
  '| Requirement | Priority | Tasks (status) | Tests | Commits |',
  '| --- | --- | --- | --- | --- |',
  ...[...reqs.values()].map((r) => {
    const commits = r.tasks.flatMap((t) => taskCommits.get(t.id) ?? []);
    return `| ${r.id} ${r.title} | ${r.priority} | ${cell(r.tasks.map((t) => `[${t.id}](../tasks/${t.file}) (${t.status})`))} | ${cell([...r.tests])} | ${cell([...new Set(commits)].slice(0, 5))} |`;
  }),
  '',
  '## Problems',
  '',
  ...(problems.length ? problems.map((p) => `- ${p}`) : ['None.']),
  '',
];
writeFileSync(join(root, 'docs/traceability.md'), out.join('\n'));
console.log(
  `Wrote docs/traceability.md (${reqs.size} requirements, ${tasks.length} tasks, ${problems.length} problems)`,
);
if (process.argv.includes('--strict') && problems.length) process.exit(1);

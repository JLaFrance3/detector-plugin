#!/usr/bin/env node
// Analyzes eval/results.csv (TASK-022, REQ-NF-006): false positive rate and detection rate
// across thresholds, the threshold T that keeps real-photo false positives at or below 5%,
// and a chart for the presentation.
// Usage: node eval/analyze.mjs   (run.mjs calls this after scoring)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const MAX_FPR = 0.05;

const NEWLINE = String.fromCharCode(10);
const [header, ...lines] = readFileSync(join(here, 'results.csv'), 'utf8').trim().split(NEWLINE);
const columns = header.split(',');
const rows = lines.map((line) => {
  const cells = line.split(',');
  const row = Object.fromEntries(columns.map((c, i) => [c, cells[i]]));
  row.score = row.score === '' ? null : Number(row.score);
  return row;
});

// Only images the detector actually scored count toward detector accuracy.
const scored = rows.filter((r) => r.score !== null);
const of = (label, variant) =>
  scored.filter((r) => r.label === label && (variant === undefined || r.variant === variant));
const rate = (set, t) => (set.length ? set.filter((r) => r.score >= t).length / set.length : 0);
const pct = (x) => `${(x * 100).toFixed(1)}%`;

const real = of('real');
const ai = of('ai');

// Smallest threshold (to two decimals, never below 0.50) with real-photo FPR <= 5%.
let chosen = 0.99;
for (let t = 50; t <= 99; t++) {
  if (rate(real, t / 100) <= MAX_FPR) {
    chosen = t / 100;
    break;
  }
}

const thresholds = [0.5, 0.6, 0.7, 0.8, 0.9, 0.95, 0.99];
if (!thresholds.includes(chosen)) thresholds.push(chosen);
thresholds.sort((a, b) => a - b);

const groups = [...new Set(ai.map((r) => r.group))];
const out = [];
out.push('# Detector evaluation results', '');
out.push('Generated by `extension/eval/analyze.mjs` from `results.csv`. Do not edit by hand.', '');
out.push('## Set', '');
out.push(
  `- ${rows.length} images scored through the extension's own pipeline (${rows.filter((r) => r.variant === 'original').length} originals and ${rows.filter((r) => r.variant === 'recompressed').length} recompressed copies: 60% size, JPEG quality 50).`,
);
out.push(
  `- AI: ${of('ai', 'original').length} originals from ${groups.length} generators (${groups.join(', ')}). Real: ${of('real', 'original').length} photographs (Wikimedia Commons Quality images).`,
);
const skipped = rows.length - scored.length;
out.push(
  `- ${skipped} image(s) were decided by provenance or metadata before the detector ran and are left out of the rates below.`,
  '',
);
out.push('## Rates by threshold', '');
out.push(
  '| Threshold T | False positives (real photos) | Detection (AI, all) | Detection (AI originals) | Detection (AI recompressed) |',
);
out.push('| --- | --- | --- | --- | --- |');
for (const t of thresholds) {
  const mark = t === chosen ? ' **(chosen)**' : '';
  out.push(
    `| ${t.toFixed(2)}${mark} | ${pct(rate(real, t))} | ${pct(rate(ai, t))} | ${pct(rate(of('ai', 'original'), t))} | ${pct(rate(of('ai', 'recompressed'), t))} |`,
  );
}
out.push('', `## Chosen threshold: T = ${chosen.toFixed(2)}`, '');
out.push(
  `The lowest threshold with a real-photo false positive rate of at most 5% (REQ-NF-006). At T = ${chosen.toFixed(2)}: false positive rate ${pct(rate(real, chosen))} (${real.filter((r) => r.score >= chosen).length} of ${real.length}), detection rate ${pct(rate(ai, chosen))} (${ai.filter((r) => r.score >= chosen).length} of ${ai.length}).`,
  '',
);
out.push('## Detection by generator at the chosen threshold', '');
out.push('| Generator | Originals | Recompressed |', '| --- | --- | --- |');
for (const group of groups) {
  const g = (variant) => ai.filter((r) => r.group === group && r.variant === variant);
  out.push(
    `| ${group} | ${pct(rate(g('original'), chosen))} (${g('original').length}) | ${pct(rate(g('recompressed'), chosen))} (${g('recompressed').length}) |`,
  );
}
const falsePositives = real.filter((r) => r.score >= chosen);
out.push('', '## Real photos flagged at the chosen threshold', '');
out.push(
  falsePositives.length
    ? falsePositives
        .map((r) => `- ${r.id} (${r.variant}), score ${r.score.toFixed(3)}`)
        .join(NEWLINE)
    : 'None.',
);
out.push('', '## Limits of this evaluation', '');
out.push(
  '- The set is small and comes from one source. Rates have wide margins: with 120 real images, one image is 0.8 percentage points.',
);
out.push(
  '- Two entries were removed after a manual look (a screenshot of a user interface and an AI-enhanced real photo); they stay in `manifest.json` marked `excluded`. The rest of the labels were not individually verified.',
);
out.push(
  '- Commons categories are user-assigned, so a few labels may be wrong, and many images predate the detector and could have been in its training data. Expect lower detection on new generators.',
);
out.push(
  '- Only one kind of degradation (downscale plus JPEG recompression) was tested; screenshots, crops and filters were not.',
);
out.push('', '![Detection and false positive rate by threshold](threshold-chart.svg)', '');
writeFileSync(join(here, 'RESULTS.md'), out.join(NEWLINE));

// --- Chart ------------------------------------------------------------------------------
const W = 720;
const H = 400;
const pad = { left: 60, right: 20, top: 30, bottom: 50 };
const x = (t) => pad.left + ((t - 0.5) / 0.5) * (W - pad.left - pad.right);
const y = (v) => pad.top + (1 - v) * (H - pad.top - pad.bottom);
const steps = Array.from({ length: 101 }, (_, i) => 0.5 + i * 0.005);
const path = (set) =>
  steps.map((t, i) => `${i ? 'L' : 'M'}${x(t).toFixed(1)},${y(rate(set, t)).toFixed(1)}`).join(' ');
const svg = [
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" font-family="system-ui, sans-serif" font-size="13">`,
  `<rect width="${W}" height="${H}" fill="#fff"/>`,
  `<text x="${pad.left}" y="18" font-size="15" font-weight="600">Detection and false positive rate by threshold</text>`,
];
for (const v of [0, 0.25, 0.5, 0.75, 1]) {
  svg.push(
    `<line x1="${pad.left}" x2="${W - pad.right}" y1="${y(v)}" y2="${y(v)}" stroke="#ddd"/>`,
  );
  svg.push(`<text x="${pad.left - 8}" y="${y(v) + 4}" text-anchor="end">${v * 100}%</text>`);
}
for (const t of [0.5, 0.6, 0.7, 0.8, 0.9, 1]) {
  svg.push(
    `<text x="${x(t)}" y="${H - pad.bottom + 20}" text-anchor="middle">${t.toFixed(1)}</text>`,
  );
}
svg.push(
  `<text x="${(W + pad.left) / 2}" y="${H - 10}" text-anchor="middle">Threshold T (detector score)</text>`,
);
svg.push(
  `<line x1="${pad.left}" x2="${W - pad.right}" y1="${y(MAX_FPR)}" y2="${y(MAX_FPR)}" stroke="#c0392b" stroke-dasharray="4 4"/>`,
);
svg.push(
  `<text x="${W - pad.right}" y="${y(MAX_FPR) - 6}" text-anchor="end" fill="#c0392b">5% false positive limit</text>`,
);
svg.push(
  `<line x1="${x(chosen)}" x2="${x(chosen)}" y1="${pad.top}" y2="${H - pad.bottom}" stroke="#555" stroke-dasharray="2 4"/>`,
);
svg.push(`<text x="${x(chosen) + 6}" y="${pad.top + 14}">T = ${chosen.toFixed(2)}</text>`);
svg.push(
  `<path d="${path(of('ai', 'original'))}" fill="none" stroke="#1f6feb" stroke-width="2.5"/>`,
);
svg.push(
  `<path d="${path(of('ai', 'recompressed'))}" fill="none" stroke="#1f6feb" stroke-width="2.5" stroke-dasharray="7 5"/>`,
);
svg.push(`<path d="${path(real)}" fill="none" stroke="#c0392b" stroke-width="2.5"/>`);
const legend = [
  ['#1f6feb', '', 'AI images detected (originals)'],
  ['#1f6feb', '7 5', 'AI images detected (recompressed)'],
  ['#c0392b', '', 'Real photos flagged (false positives)'],
];
legend.forEach(([color, dash, label], i) => {
  const ly = pad.top + 60 + i * 20;
  svg.push(
    `<line x1="${pad.left + 20}" x2="${pad.left + 50}" y1="${ly}" y2="${ly}" stroke="${color}" stroke-width="2.5" stroke-dasharray="${dash}"/>`,
  );
  svg.push(`<text x="${pad.left + 58}" y="${ly + 4}">${label}</text>`);
});
svg.push('</svg>');
writeFileSync(join(here, 'threshold-chart.svg'), svg.join(NEWLINE) + NEWLINE);

console.log(
  `chosen threshold T = ${chosen.toFixed(2)}: FPR ${pct(rate(real, chosen))}, detection ${pct(rate(ai, chosen))} (${scored.length} scored images)`,
);

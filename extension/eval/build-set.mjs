#!/usr/bin/env node
// Builds the labelled evaluation set for TASK-022 (REQ-NF-006) from Wikimedia Commons:
// AI images from several generators (by category) and real photographs (Quality images).
//
// Usage: node eval/build-set.mjs            download the images listed in eval/manifest.json
//        node eval/build-set.mjs --extend   keep the manifest and top each source up to its count
//        node eval/build-set.mjs --refresh  pick a new random selection and rewrite the manifest
//
// The manifest (titles, labels, source pages) is committed so the set is reproducible; the
// image files go to e2e/output/eval-set/ and are not committed.
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const manifestPath = join(here, 'manifest.json');
export const setDir = join(here, '..', 'e2e', 'output', 'eval-set');
const USER_AGENT = 'aid-eval/0.1 (student course project; AI image detector evaluation)';
const WIDTH = 960;

/** Commons searches per generator, and how many images to take from each. */
const sources = [
  { label: 'ai', group: 'Midjourney', search: 'deepcategory:"Midjourney"', count: 13 },
  { label: 'ai', group: 'DALL-E', search: 'deepcategory:"DALL-E"', count: 13 },
  { label: 'ai', group: 'Stable Diffusion', search: 'deepcategory:"Stable Diffusion"', count: 13 },
  {
    label: 'ai',
    group: 'Flux',
    search: 'deepcategory:"Flux (text-to-image model)"|"Images generated by Flux AI"',
    count: 8,
  },
  {
    label: 'ai',
    group: 'Imagen',
    search: 'deepcategory:"Imagen (Google)"|"Images generated by Google Imagen"',
    count: 6,
  },
  {
    label: 'ai',
    group: 'Leonardo AI',
    search: 'deepcategory:"AI-generated images by Leonardo AI"',
    count: 6,
  },
  { label: 'ai', group: 'Meta AI', search: 'deepcategory:"Images generated by Meta AI"', count: 5 },
  // Photographs taken by Commons contributors and reviewed for technical quality.
  { label: 'real', group: 'Quality images', search: 'incategory:"Quality images"', count: 64 },
];

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function api(params) {
  const url = new URL('https://commons.wikimedia.org/w/api.php');
  for (const [k, v] of Object.entries({ format: 'json', ...params })) url.searchParams.set(k, v);
  for (let attempt = 0; attempt < 5; attempt++) {
    const response = await fetch(url, { headers: { 'user-agent': USER_AGENT } });
    if (response.ok) return response.json();
    await sleep(5000 * (attempt + 1));
  }
  throw new Error(`Commons API failed for ${url}`);
}

/** Picks images for a source until it has `count`, skipping titles already in `taken`. */
async function pick(source, existing, taken) {
  const items = [...existing];
  for (let round = 0; round < 4 && items.length < source.count; round++) {
    const data = await api({
      action: 'query',
      generator: 'search',
      gsrnamespace: '6',
      gsrlimit: '50',
      gsrsort: 'random',
      // JPEG only, and large enough that a 960 px rendition is not an upscale.
      gsrsearch: `${source.search} filemime:image/jpeg filew:>900 fileh:>500`,
      prop: 'imageinfo',
      iiprop: 'url|size|mime|extmetadata',
      iiextmetadatafilter: 'LicenseShortName',
      iiurlwidth: String(WIDTH),
    });
    for (const page of Object.values(data.query?.pages ?? {})) {
      const info = page.imageinfo?.[0];
      if (!info?.thumburl || taken.has(page.title)) continue;
      // Skip derivative works that mix real and generated content.
      if (
        /upscal|retouch|restor|coloriz|edited|collage|comparison|diagram|logo|map/i.test(page.title)
      ) {
        continue;
      }
      taken.add(page.title);
      const slug = source.group.toLowerCase().replace(/[^a-z0-9]+/g, '-');
      items.push({
        id: `${source.label}-${slug}-${String(items.length + 1).padStart(2, '0')}`,
        label: source.label,
        group: source.group,
        title: page.title,
        page: info.descriptionurl,
        license: info.extmetadata?.LicenseShortName?.value ?? 'see source page',
        url: info.thumburl.split('?')[0],
      });
      if (items.length === source.count) break;
    }
    await sleep(1500);
  }
  if (items.length < source.count) {
    console.warn(`only ${items.length} of ${source.count} images for ${source.group}`);
  }
  return items;
}

async function loadManifest() {
  let current = [];
  try {
    current = JSON.parse(await readFile(manifestPath, 'utf8'));
  } catch {
    // no manifest yet: build one
  }
  const refresh = process.argv.includes('--refresh');
  const extend = process.argv.includes('--extend');
  if (current.length > 0 && !refresh && !extend) return current;
  if (refresh) current = [];

  // --extend keeps what is already there and tops each source up to its count.
  const taken = new Set(current.map((item) => item.title));
  const items = [];
  for (const source of sources) {
    const existing = current.filter((item) => item.group === source.group);
    items.push(...(await pick(source, existing, taken)));
  }
  await writeFile(manifestPath, `${JSON.stringify(items, null, 2)}\n`);
  console.log(`wrote ${items.length} entries to eval/manifest.json`);
  return items;
}

const manifest = await loadManifest();
await mkdir(setDir, { recursive: true });
let downloaded = 0;
for (const item of manifest) {
  const file = join(setDir, `${item.id}.jpg`);
  if (await stat(file).catch(() => null)) continue;
  for (let attempt = 0; ; attempt++) {
    const response = await fetch(item.url, { headers: { 'user-agent': USER_AGENT } });
    if (response.ok) {
      await writeFile(file, Buffer.from(await response.arrayBuffer()));
      downloaded++;
      break;
    }
    if (attempt >= 5) throw new Error(`download failed for ${item.title}: HTTP ${response.status}`);
    await sleep(15000 * (attempt + 1)); // Commons rate-limits bursts
  }
  await sleep(3000);
}
const counts = {};
for (const item of manifest) counts[item.group] = (counts[item.group] ?? 0) + 1;
console.log(`set ready: ${manifest.length} images (${downloaded} downloaded now)`, counts);
